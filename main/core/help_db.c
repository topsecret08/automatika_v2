const size_t HELP_ARTICLES_COUNT =
    sizeof(HELP_ARTICLES) / sizeof(HELP_ARTICLES[0]);

void help_init(void) {
    ESP_LOGI(TAG, "Встроенная справка: %u статей",
             (unsigned)HELP_ARTICLES_COUNT);
    if (sd_content_ready()) {
        char names[16][SD_CONTENT_MAX_NAME];
        int n = sd_content_list(CT_HELP, names, 16);
        ESP_LOGI(TAG, "Статей на SD: %d", n);
    }
}

const help_article_t* help_find(const char *id) {
    if (!id) return NULL;
    for (size_t i = 0; i < HELP_ARTICLES_COUNT; i++) {
        if (strcmp(HELP_ARTICLES[i].id, id) == 0) return &HELP_ARTICLES[i];
    }
    return NULL;
}

bool help_show_article(const char *id) {
    if (!id) return false;

    const help_article_t *a = help_find(id);
    if (a) {
        ui_show_markdown(a->title, a->content_md);
        return true;
    }

    static char buf[4096];
    char name[96];
    snprintf(name, sizeof(name), "%s.md", id);

    if (sd_content_read(CT_HELP, name, buf, sizeof(buf))) {
        ui_show_markdown(id, buf);
        return true;
    }

    snprintf(buf, sizeof(buf),
             "# Статья не найдена\n\n"
             "Встроенной статьи `%s` нет, а файл\n"
             "`/sdcard/help/%s.md` отсутствует.\n\n"
             "Скопируйте папку `sdcard/` из репозитория на карту\n"
             "(скрипт `generate_sdcard.py`).", id, id);
    ui_show_markdown("Справка", buf);
    ESP_LOGW(TAG, "Нет статьи: %s", id);
    return false;
}
