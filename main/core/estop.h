#pragma once
#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"

// Аппаратная аварийная кнопка E-STOP.
//
// Требование: нормально замкнутый контакт NC, вход с подтяжкой вверх
// (ESTOP_GPIO). В нормальном состоянии линия притянута к GND (0), нажатие
// размыкает её и pull-up даёт 1 — срабатывает прерывание по возрастающему
// фронту. Высокий уровень также означает обрыв провода и считается
// аварийным. Короткое замыкание линии на GND неотличимо от нормы — это
// ограничение схемы, для него нужен отдельный диагностический канал.
//
// В отличие от исходного примера, нажатие НЕ снимается автоматически:
// защёлка держится до отпускания кнопки и осознанного сброса аварии
// (ctrl_safety_reset). Уровень линии перепроверяется при каждой проверке,
// поэтому потерянное прерывание или дребезг не позволяют управлять
// нагревом.

esp_err_t estop_init(void);
void      estop_task(void *arg);

// true — авария активна (кнопка нажата или защёлка не снята).
bool      estop_is_pressed(void);
// Состояние линии сейчас: true — кнопка нажата (разомкнут NC-контакт).
bool      estop_button_down(void);
int       estop_raw_level(void);
// Сброс защёлки только если кнопка отпущена и авария снята.
bool      estop_acknowledge(void);
// Программная блокировка (Lua/диагностика): защёлка ставится до reset.
void      estop_force(const char *reason);
const char *estop_source_name(void);
uint32_t  estop_since_ms(void);
